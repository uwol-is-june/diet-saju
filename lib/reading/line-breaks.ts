/**
 * 문장 묶음 단위 줄바꿈 (TASK-28 → TASK-80).
 *
 * 풀이 본문이 한 문단에 여러 문장으로 붙어 나와 벽처럼 읽힌다는 요청에서 나왔다(TASK-28).
 * 그때는 **모든 문장을 문단으로** 갈랐는데, 이번에는 반대쪽으로 넘어가 있었다 —
 * 한 문장짜리 문단이 스무 개쯤 이어져 호흡이 끊기고 글이 목록처럼 읽혔다
 * (`diet` 실측 3,208자에서 문단 48개 · 2026-08-19). 그래서 **문장 경계에서 가르되
 * 덩어리가 일정 길이를 넘었을 때만** 가르도록 바꿨다.
 *
 * ## 프롬프트로 풀지 않은 이유
 *
 * "문장마다 줄을 바꿔 달라" 고 부탁해도 **화면에서는 안 바뀐다.** `react-markdown` 은
 * CommonMark 라 단일 개행을 줄바꿈으로 렌더하지 않고 공백 하나로 이어 붙인다
 * (`remark-breaks` 같은 플러그인이 없다 — `package.json` 확인). 모델이 개행을 넣어도
 * 결과가 같으므로, 형식은 **렌더 직전에 코드가** 만든다. 프롬프트에 의존하지 않으니
 * 모델이 어떻게 쓰든 같은 모양이 나온다.
 *
 * ## 왜 `<br>` 이 아니라 문단인가
 *
 * CommonMark 의 hard break(`  \n` → `<br>`)를 쓰면 줄 간격이 본문 줄 간격과 같아서,
 * **모바일에서 한 문장이 여러 줄로 접히는 순간 문장 경계가 보이지 않는다.** 390px 에서
 * 한국어 한 문장은 보통 두세 줄을 쓴다. 그래서 문단으로 끊어 `.reading p` 의 여백이
 * 경계를 만들게 했다. 폭과 무관하게 구분이 유지된다.
 *
 * ## 묶는 규칙은 하나다 — 길이 문턱
 *
 * 문장 경계를 왼쪽부터 훑다가 **쌓인 덩어리가 `CHUNK_MIN_CHARS` 를 넘으면 거기서** 가른다.
 * 규칙 하나로 두 가지가 함께 풀린다.
 *
 *  - **모델이 이미 넣은 문단 경계가 산다.** 변환이 줄 단위라 모델의 빈 줄은 애초에 넘지
 *    않고, 문턱보다 짧은 문단은 손대지 않는다.
 *  - **긴 문단만 갈린다.** 200자짜리 문단이 100자 안팎의 덩어리 둘로 나뉜다.
 *
 * "두세 문장씩" 을 문장 **수**로 세지 않은 것은, 같은 두 문장이라도 길이가 30자에서
 * 120자까지 흔들려 화면에서 보이는 덩어리 크기가 세 배씩 차이 나기 때문이다. 읽는
 * 사람이 느끼는 것은 문장 수가 아니라 줄 수다.
 *
 * `CHUNK_MIN_CHARS = 80` 은 **우리 관례**다. 근거는 390px 실측이다 — 이 폭에서 본문
 * 한 줄이 24자 안팎이고 풀이 한 문장이 50~65자(두세 줄)다. 문턱을 80자에 두면 덩어리가
 * 대개 두 문장 · 95~107자 · **4~5줄**이 된다 (표본 둘: `diet` 문단 48→29개 · 평균
 * 65→107자, `diet-method` 32→18개 · 53→95자 · 2026-08-19).
 *
 * 문턱을 60자로 내리면 3.9줄이 되어 다시 한 문장짜리 문단이 섞이고, 120자로 올리면
 * 가장 긴 문단이 200자(9줄)를 넘어 TASK-28 이 없앤 벽이 돌아온다. **문장을 쪼개지는
 * 않으므로** 100자가 넘는 긴 문장은 그대로 혼자 문단이 된다.
 *
 * ## 마침표가 문장 끝이 아닌 경우
 *
 * `3.5kg`, `1. 항목`, `e.g.` 처럼 마침표가 문장을 끝내지 않는 자리가 있다. 그래서
 * **종결 부호 앞 글자가 한글이거나 닫는 괄호·따옴표일 때만** 가른다. 숫자·영문 뒤의
 * 마침표는 애초에 걸리지 않으므로 예외 목록을 관리할 필요가 없다.
 *
 * ## 스트리밍 중에 줄이 튀지 않는다
 *
 * 파서가 누적 문자열을 매 조각 다시 파싱하므로 이 변환도 매번 다시 돈다. 그래서
 * **종결 부호 뒤에 공백과 다음 글자가 모두 도착했을 때만** 가른다. 마지막 문장이
 * 쓰이는 중에는 조건이 성립하지 않아 줄이 생겼다 사라지지 않는다.
 *
 * 묶기를 넣어도 이 성질은 그대로다. **왼쪽부터 훑는 그리디**라 어느 경계에서 가를지가
 * 그 앞의 글자에만 달려 있고, 뒤에 글이 더 붙어도 이미 내린 결정이 바뀌지 않는다.
 * (문장 수를 뒤에서부터 맞추거나 문단 전체 길이를 보고 균등 분할하는 방식이었다면
 * 마지막 문장이 도착할 때마다 앞쪽 경계가 움직여 읽던 자리가 튄다.)
 */

/** 코드 울타리. 모델이 쓸 일은 없지만 들어오면 안쪽을 건드리지 않는다. */
const FENCE = /^\s*(?:```|~~~)/;

/**
 * 문장을 가르지 않는 줄 — 제목, 목록 항목, 인용, 표.
 * 목록 줄을 가르면 항목 하나가 여러 문단으로 쪼개져 목록 구조가 깨진다.
 */
const STRUCTURAL_LINE = /^\s*(?:#{1,6}\s|[-*+]\s|\d+[.)]\s|>|\||:?-{3,})/;

/**
 * 종결 부호 + 공백 + 다음 글자.
 *
 * 앞 글자를 `[가-힣]` 과 닫는 괄호·따옴표로 한정해 `3.5` · `1. 항목` · `e.g.` 를 피한다.
 * 종결 부호를 `+` 로 받는 것은 `…?!` 처럼 겹쳐 쓰는 경우 때문이다.
 */
const SENTENCE_END = /([가-힣)\]』」”’"'])([.!?]+)[ \t]+(?=\S)/g;

/**
 * 한 덩어리의 길이 문턱(글자). **우리 관례** — 근거는 파일 첫머리 주석.
 *
 * 이 값을 넘긴 뒤 처음 만나는 문장 끝에서 가른다. 그래서 실제 덩어리는 문턱보다
 * 길어질 수 있고(문장을 쪼개지 않으므로) 짧아지지는 않는다.
 */
const CHUNK_MIN_CHARS = 80;

/** 문단 사이 빈 줄이 셋 이상 겹치면 하나로 줄인다 (모델이 이미 넣은 것과 겹칠 수 있다). */
const EXTRA_BLANK_LINES = /\n{3,}/g;

/**
 * 한 줄(= 모델이 낸 문단 하나)을 문장 묶음으로 가른다.
 *
 * 왼쪽부터 그리디로 훑는다 — 쌓인 길이가 문턱을 넘은 뒤 처음 만나는 문장 끝이 경계다.
 */
function chunkLine(line: string): string {
  SENTENCE_END.lastIndex = 0;

  let result = "";
  let chunkStart = 0;
  let match: RegExpExecArray | null;

  while ((match = SENTENCE_END.exec(line)) !== null) {
    // 문장이 끝나는 자리 = 종결 부호 뒤. 뒤따르는 공백은 경계가 되면 버린다.
    const sentenceEnd = match.index + match[1].length + match[2].length;
    if (sentenceEnd - chunkStart < CHUNK_MIN_CHARS) continue;

    result += `${line.slice(chunkStart, sentenceEnd)}\n\n`;
    chunkStart = match.index + match[0].length;
  }

  return result + line.slice(chunkStart);
}

/**
 * 마크다운 본문을 문장 묶음 단위로 끊는다.
 *
 * 순수 함수이고 클라이언트에서 import 되므로 `server-only` 를 붙이지 않는다
 * (`lib/reading/sections.ts` 와 같은 이유).
 */
export function breakSentences(markdown: string): string {
  if (!markdown) return markdown;

  let inFence = false;
  const lines = markdown.split("\n").map((line) => {
    if (FENCE.test(line)) {
      inFence = !inFence;
      return line;
    }
    if (inFence || STRUCTURAL_LINE.test(line)) return line;
    return chunkLine(line);
  });

  return lines.join("\n").replace(EXTRA_BLANK_LINES, "\n\n");
}
